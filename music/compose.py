"""Compile songs.py + the SFX designs into C tables for src/sound.c."""
import re
from songs import SONGS, ORDER
CLOCK = 3579545
NOTE0 = 'A2'
NAMES = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7, 'G#': 8, 'A': 9, 'A#': 10, 'B': 11}
def midi(tok):
    m = re.match(r'([A-G]#?)(\d)$', tok); return NAMES[m[1]] + 12 * (int(m[2]) + 1)
BASE = midi('A2')
def period(n): return round(CLOCK / (32 * 440.0 * 2 ** ((n - 69) / 12.0)))
NNOTES = 62
periods = [period(BASE + i) for i in range(NNOTES)]
assert periods[0] <= 1023
def tok_byte(t, drum=False):
    if t == '.': return 0
    if t == '-': return 1
    if drum: return {'K': 2, 'S': 3, 'h': 4, 'o': 5}[t]
    arp = 0
    if t[-1] in 'mM' and t[-2].isdigit(): arp = 1 if t[-1] == 'm' else 2; t = t[:-1]
    n = midi(t) - BASE
    assert 0 <= n < NNOTES, t
    return (arp << 6) | (n + 2)
pats, pid = [], {}
def pat(bar, drum=False):
    toks = bar.split(); assert len(toks) == 16, bar
    b = tuple(tok_byte(t, drum) for t in toks)
    if b not in pid: pid[b] = len(pats); pats.append(b)
    return pid[b]
INS = {'pluck': 0, 'lead': 1, 'pad': 2}
out = ['/* generated by music/compose.py - original music for this port */', '#include <stdint.h>', '#include "music_data.h"']
songs_c = []
orders_all = []
for name in ORDER:
    s = SONGS[name]
    chans = [s['ch0'], s['ch1'], s['ch2'], s['noise']]
    n = max(len(c) for c in chans)
    for c in chans: assert len(c) == n, (name, [len(c) for c in chans])
    start = len(orders_all)
    for i in range(n):
        orders_all += [pat(chans[0][i]), pat(chans[1][i]), pat(chans[2][i]), pat(chans[3][i], True)]
    loop = 0xFF if s['loop'] is None else s['loop']
    songs_c.append('{%d, %d, %d, %d}' % (s['tempo'], n, loop, start // 4))
out.append('const uint16_t note_period[%d] = {%s};' % (NNOTES, ','.join(map(str, periods))))
out.append('const uint8_t mus_pat[%d][16] = {%s};' % (len(pats), ','.join('{' + ','.join(map(str, p)) + '}' for p in pats)))
out.append('const uint8_t mus_order[%d] = {%s};' % (len(orders_all), ','.join(map(str, orders_all))))
out.append('const song_t mus_songs[%d] = {%s};' % (len(ORDER), ','.join(songs_c)))
open('../src/music_data.c', 'w').write('\n'.join(out) + '\n')
h = ['#ifndef MUSIC_DATA_H', '#define MUSIC_DATA_H', '#include <stdint.h>',
     'typedef struct { uint8_t tempo, nbars, loop; uint16_t order0; } song_t;',
     'extern const uint16_t note_period[%d];' % NNOTES, 'extern const uint8_t mus_pat[][16];',
     'extern const uint8_t mus_order[];', 'extern const song_t mus_songs[];']
for i, name in enumerate(ORDER): h.append('#define SONG_%s %d' % (name.upper(), i))
h.append('#endif')
open('../src/music_data.h', 'w').write('\n'.join(h) + '\n')
print(len(pats), 'patterns', len(orders_all), 'order bytes', sum(16 for p in pats) + len(orders_all), 'bytes')
